export function getHomeContent(siteKey, locale) {
  if (siteKey === 'web') return homeContent.web[locale];
  if (familyHomeContent[locale]?.[siteKey]) return familyHomeContent[locale][siteKey];

  const generic = genericByLocale[locale];
  const index = ['calc', 'convert', 'text', 'dev', 'ai'].indexOf(siteKey);
  const heading = localeNames[locale]?.[index] ?? siteMeta[siteKey].siteName;
  return {
    title: `${siteMeta[siteKey].siteName} - ${heading}`,
    description: siteDescriptions[siteKey],
    label: generic.label,
    heading,
    intro: generic.intro,
    note: generic.note,
    collection: generic.collection,
    explainTitle: generic.explainTitle,
    explain: generic.explain,
    tools: siteToolSets[siteKey],
  };
}
